// Generate an idempotent seed migration of the WHO IEHK medical catalog
// (categories + products) straight from public/suministros-medicos.html, so the
// Suministros product database mirrors the medical-supplies list shown on the site.
// Reference data only — names/units/categories/descriptions, ZERO stock.
//   node scripts/gen-medicos-seed.mjs > migrations/0078_sum_medicos_seed.sql
import { readFileSync } from 'node:fs';

const html = readFileSync('public/suministros-medicos.html', 'utf8');

function slice(start, end) {
  const i = html.indexOf(start); const j = html.indexOf(end, i);
  return html.slice(i + start.length, j);
}

// CATS: { 'Nombre':'#hex', ... }
const CATS = eval('({' + slice('const CATS = {', '};') + '})');
// D array rows: [cat,dci,marca,pres,base,unit,cold,ctrl]
const D = eval('[' + slice('const D = [', '].map(r=>') + ']');
// EXTRA: descriptions keyed "dci|marca" → [english, usos, dosis]
const EXTRA = eval('({' + slice('const EXTRA = {', '};') + '})');

const FIXED_MS = 1782518400000; // match existing seed timestamp → deterministic
const sql = (s) => (s == null ? 'NULL' : `'${String(s).replace(/'/g, "''").slice(0, 1000)}'`);
const slug = (s) => 'med_' + String(s).normalize('NFD').replace(/[̀-ͯ]/g, '')
  .toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 40);

// Unit code → readable canonical unit (kept in sync with sum_productos UNIDADES).
const UNIT = { L: 'litro', mL: 'ml', amp: 'ampolla', tab: 'tableta', vial: 'vial',
  dosis: 'dosis', bolsa: 'bolsa', frasco: 'frasco', par: 'par', sobre: 'sobre',
  set: 'set', u: 'unidad' };

const out = [];
out.push('-- SUMINISTROS — WHO IEHK medical catalog seed (categories + products).');
out.push('-- Generated by scripts/gen-medicos-seed.mjs from public/suministros-medicos.html.');
out.push('-- Reference catalog only (names/units/categories/usos) — ZERO stock. Idempotent.');
out.push('');

// Categories (cat_med_<slug>) — idempotent.
const catId = new Map();
out.push('INSERT OR IGNORE INTO sum_categorias (id, nombre, color, descripcion, created_ms) VALUES');
const catRows = Object.entries(CATS).map(([nombre, color]) => {
  const id = 'cat_' + slug(nombre);
  catId.set(nombre, id);
  return `  (${sql(id)}, ${sql(nombre)}, ${sql(color)}, ${sql('Categoría médica (IEHK OMS)')}, ${FIXED_MS})`;
});
out.push(catRows.join(',\n') + ';');
out.push('');

// Products (prod_med_<slug>) — idempotent. perecedero=1 if cold-chain or controlled.
out.push('INSERT OR IGNORE INTO sum_productos');
out.push('  (id, codigo, nombre, categoria_id, unidad, perecedero, stock_min, descripcion, costo_unit, activo, created_ms, updated_ms) VALUES');
const seen = new Set();
const prodRows = [];
let n = 0;
for (const r of D) {
  const [cat, dci, marca, pres, , unit, cold, ctrl] = r;
  let id = 'prod_' + slug(dci + '_' + marca);
  if (seen.has(id)) id = id + '_' + (++n);  // de-dupe identical dci/marca
  seen.add(id);
  const codigo = 'MED-' + String(++n).padStart(4, '0');
  const ex = EXTRA[dci + '|' + marca];
  const desc = [pres, ex && ex[1] ? ex[1] : ''].filter(Boolean).join(' · ');
  const unidad = UNIT[unit] || 'unidad';
  const perecedero = (cold || ctrl) ? 1 : 0;
  prodRows.push(`  (${sql(id)}, ${sql(codigo)}, ${sql(dci)}, ${sql(catId.get(cat))}, ${sql(unidad)}, ${perecedero}, 0, ${sql(desc)}, 0, 1, ${FIXED_MS}, ${FIXED_MS})`);
}
out.push(prodRows.join(',\n') + ';');
out.push('');

process.stdout.write(out.join('\n'));
process.stderr.write(`# ${catRows.length} categories, ${prodRows.length} products\n`);
