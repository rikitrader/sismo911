// Generates migrations/0047_rbac_seed.sql from the canonical rbac-catalog.mjs.
// Idempotent INSERT OR IGNOREs. Run: node scripts/gen-rbac-seed.mjs
import { PERMISSIONS, ROLES, MODULES, FIELD_POLICIES } from './rbac-catalog.mjs';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const q = (s) => (s == null ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`);
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'migrations', '0047_rbac_seed.sql');

let sql = `-- ============================================================================
-- 0047_rbac_seed.sql — GENERATED by scripts/gen-rbac-seed.mjs. DO NOT EDIT BY HAND.
-- Source of truth: scripts/rbac-catalog.mjs. Regenerate after catalog changes.
--
-- Seeds the permission catalog, system roles + their DIRECT grants (inheritance
-- is resolved at runtime from rbac_roles.inherits_json), per-module feature flags,
-- default field policies, and backfills user_roles from the legacy users.role so
-- existing admins/operators keep working through the new engine unchanged.
-- All idempotent (INSERT OR IGNORE).
-- ============================================================================

`;

// permission catalog
sql += `-- Permission catalog (${PERMISSIONS.length} permissions)\n`;
sql += `INSERT OR IGNORE INTO rbac_permissions (key, resource, action, label, category) VALUES\n`;
sql += PERMISSIONS.map((p) => ` (${q(p.key)},${q(p.resource)},${q(p.action)},${q(p.label)},${q(p.category)})`).join(',\n') + ';\n\n';

// feature flags (all modules enabled by default for the single org)
sql += `-- Feature flags (modules enabled by default)\n`;
sql += `INSERT OR IGNORE INTO feature_flags (org_id, module_key, enabled, updated_ms) VALUES\n`;
sql += MODULES.map((m) => ` ('org_sismo911',${q(m)},1,0)`).join(',\n') + ';\n\n';

// roles
sql += `-- System roles (${ROLES.length})\n`;
sql += `INSERT OR IGNORE INTO rbac_roles (id, org_id, key, name, description, inherits_json, is_system, created_ms) VALUES\n`;
sql += ROLES.map((r) => {
  const inh = JSON.stringify(r.inherits ?? []);
  return ` ('role_${r.key}',NULL,${q(r.key)},${q(r.name)},${q(r.desc)},${q(inh)},1,0)`;
}).join(',\n') + ';\n\n';

// direct role → permission grants
sql += `-- Direct role→permission grants (effect=allow). Inheritance resolved at runtime.\n`;
const grants = [];
const allKeys = PERMISSIONS.map((p) => p.key);
for (const r of ROLES) {
  const direct = r.perms === '*' ? allKeys : (r.perms ?? []);
  for (const k of direct) {
    if (!allKeys.includes(k)) throw new Error(`role ${r.key} grants unknown perm ${k}`);
    grants.push(` ('role_${r.key}',${q(k)},'allow')`);
  }
}
if (grants.length) {
  sql += `INSERT OR IGNORE INTO role_permissions (role_id, perm_key, effect) VALUES\n` + grants.join(',\n') + ';\n\n';
}

// field policies
sql += `-- Default field-level policies\n`;
sql += `INSERT OR IGNORE INTO field_policies (id, org_id, resource, field, visibility, required_perm, created_ms) VALUES\n`;
sql += FIELD_POLICIES.map((f, i) =>
  ` ('fp_${String(i + 1).padStart(3, '0')}','org_sismo911',${q(f.resource)},${q(f.field)},${q(f.visibility)},${q(f.perm ?? null)},0)`
).join(',\n') + ';\n\n';

// backfill user_roles from legacy users.role
sql += `-- Backfill: map legacy users.role → new system roles (preserves live access)\n`;
sql += `INSERT OR IGNORE INTO user_roles (user_id, role_id, granted_ms)
  SELECT u.id,
         'role_' || (CASE u.role WHEN 'admin' THEN 'super_admin' WHEN 'operator' THEN 'operator' ELSE 'citizen' END),
         0
  FROM users u;\n`;

writeFileSync(OUT, sql);
console.log(`wrote ${OUT}: ${PERMISSIONS.length} perms, ${ROLES.length} roles, ${grants.length} grants, ${MODULES.length} modules`);
